vim.opt.rtp:prepend(vim.fn.getcwd())
local plugin = require("lint_tools")
local options = { events = {}, root_markers = { "lifecycle-root" } }
local caller = vim.deepcopy(options)
plugin.setup(options)
assert(vim.deep_equal(caller, options), "setup mutated caller configuration")
local commands = vim.api.nvim_get_commands({})
local handlers = vim.api.nvim_get_autocmds({})
assert(not pcall(plugin.setup, false), "setup(false) must reject an invalid configuration type")
assert(vim.deep_equal(commands, vim.api.nvim_get_commands({})), "Invalid setup replaced commands")
assert(vim.deep_equal(handlers, vim.api.nvim_get_autocmds({})), "Invalid setup replaced handlers")
plugin.setup(caller)
assert(#vim.api.nvim_get_autocmds({}) == #handlers, "Repeated setup duplicated automatic handlers")
print("lint-tools.nvim: setup input isolation, invalid configuration and registration lifetime passed")

local configured = plugin.config()
options.root_markers[1] = "caller change"
assert(plugin.config().root_markers[1] == "lifecycle-root")
assert(not pcall(plugin.setup, { timeout = -1 }))
assert(vim.deep_equal(configured, plugin.config()))
plugin.disable()
plugin.enable()
assert(vim.deep_equal(configured, plugin.config()))
vim.api.nvim_create_user_command("LintToolsInfo", function() end, { desc = "personal lint command" })
plugin.dispose()
plugin.dispose()
assert(plugin.config() == nil and #plugin.status() == 0)
assert(vim.fn.exists("#LintTools") == 0)
assert(vim.api.nvim_get_commands({}).LintToolsInfo)
vim.api.nvim_del_user_command("LintToolsInfo")
plugin.enable()
assert(plugin.config().events[1] == "BufWritePost")
plugin.dispose()
